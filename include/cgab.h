#endif

/*
 * Initial capacity of bytecode-module constant tables.
 */
#ifndef cGAB_CONSTANTS_INITIAL_CAP
#define cGAB_CONSTANTS_INITIAL_CAP 256
#endif

/*
 * TODO @cgab @bug: Fix localqueue max.
 * Queues were rewritten to be growable - this breaks the constraint
 * where we statically know a ceiling on how many values
 * can possibly be reached by a job in a given epoch.
 *
 * This is an issue because our gc buffers are statically sized,
 * and we could run out of space in the buffers. The same issue
 * arises if we add growable fiber stacks.
 *
 * The fix is to create two queues on the job - one for fibers it has begun
 * running, and one for fibers it hasn't touched yet. This actually also an
 * optimization, and can even facilitate some future work-stealing.
 *
 * By limiting the size of the working-queue, we can statically know the maximum
 * number of reachable values from a job. Fibers that have never been run don't
 * even need their stack's tracked yet.
 *
 * The number of fibers a given job may hold in its working queue.
 */
#ifndef cGAB_WORKER_LOCALQUEUE_MAX
#define cGAB_WORKER_LOCALQUEUE_MAX 32
#endif

