[[noreturn]]
static inline void __gab_assert_fail(const char *prelude, const char *expr,
                                     const char *file, const char *function,
                                     uint64_t line, const char *reason, ...) {
  va_list va;
  va_start(va, reason);

  fprintf(stdout, "\n\n%s\n[%s:%" PRId64 " %s] assertion '%s' failed: ", prelude,
          file, line, function, expr);

  vfprintf(stdout, reason, va);

  fprintf(stdout, "\n\n");

  exit(EXIT_FAILURE);
  va_end(va);
};

